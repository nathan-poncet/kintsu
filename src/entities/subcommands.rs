#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn a_program_with_a_table_is_known_under_each_of_its_names() {
        assert!(subcommands_of("git").unwrap().contains(&"status"));
        assert!(subcommands_of("pip3").unwrap().contains(&"install"));
        assert!(subcommands_of("apt-get").unwrap().contains(&"install"));
        assert_eq!(subcommands_of("ls"), None);
    }

    #[test]
    fn every_table_is_sorted_so_a_missing_entry_is_easy_to_spot() {
        for name in programs_with_subcommands() {
            let table = subcommands_of(name).unwrap();
            assert!(
                table.windows(2).all(|w| w[0] < w[1]),
                "{name} is not sorted"
            );
        }
        assert!(GIT_LONG_OPTIONS.windows(2).all(|w| w[0] < w[1]));
    }
}
