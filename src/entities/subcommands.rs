//! The programs whose first argument is a subcommand, and which ones they
//! know: for `git stauts`, `gitpush` and `git-push`.

/// The subcommands of `program`, when its first argument is one.
pub fn subcommands_of(program: &str) -> Option<&'static [&'static str]> {
    PROGRAMS
        .iter()
        .find(|(name, _)| *name == program)
        .map(|(_, subcommands)| *subcommands)
}

/// Every program with a table, for `gitpush` and `git-push`.
pub fn programs_with_subcommands() -> impl Iterator<Item = &'static str> {
    PROGRAMS.iter().map(|(name, _)| *name)
}

